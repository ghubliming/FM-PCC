class Img:
    def __init__(s,w,h,bg=(255,255,255)):
        s.w,s.h=w,h; s.px=bytearray(bytes(bg)*w*h)
    def set(s,x,y,c):
        if 0<=x<s.w and 0<=y<s.h:
            i=(y*s.w+x)*3; s.px[i]=c[0]; s.px[i+1]=c[1]; s.px[i+2]=c[2]
    def rect(s,x,y,w,h,c):
        for j in range(int(y),int(y+h)):
            for i in range(int(x),int(x+w)): s.set(i,j,c)
    def hline(s,x1,x2,y,c,t=1):
        s.rect(min(x1,x2),y,abs(x2-x1)+1,t,c)
    def vline(s,x,y1,y2,c,t=1):
        s.rect(x,min(y1,y2),t,abs(y2-y1)+1,c)
    def text(s,x,y,txt,c,sc=2,sp=1):
        cx=x
        for ch in txt.upper() if txt.upper() in FONT or True else txt:
            g=FONT.get(ch.upper() if ch.upper() in FONT else ch)
            if g is None: g=FONT[' ']
            for r,row in enumerate(g):
                for q,v in enumerate(row):
                    if v=='#': s.rect(cx+q*sc, y+r*sc, sc, sc, c)
            cx+=(5+sp)*sc
        return cx
    def tw(s,txt,sc=2,sp=1): return len(txt)*(5+sp)*sc
    def save(s,path):
        raw=b''.join(b'\x00'+bytes(s.px[j*s.w*3:(j+1)*s.w*3]) for j in range(s.h))
        def chunk(t,d):
            return struct.pack('>I',len(d))+t+d+struct.pack('>I',zlib.crc32(t+d)&0xffffffff)
        png=(b'\x89PNG\r\n\x1a\n'
             +chunk(b'IHDR',struct.pack('>IIBBBBB',s.w,s.h,8,2,0,0,0))
             +chunk(b'IDAT',zlib.compress(raw,9))
             +chunk(b'IEND',b''))
        open(path,'wb').write(png)
        return len(png)
